"""Input/topology checks for actual soot-dem coupling, no trajectories."""
from pathlib import Path
import sys,tempfile,unittest
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'tools'))
from run_pf_dem import parse_xml,prepared_text,neck_edges
ROOT=Path(__file__).resolve().parents[1]
class SootInputTests(unittest.TestCase):
    def setUp(self):self.tmp=tempfile.TemporaryDirectory();self.path=Path(self.tmp.name)
    def tearDown(self):self.tmp.cleanup()
    def test_both_coatings_keep_the_same_neck_graph(self):
        a=parse_xml(ROOT/'examples/soot_dem_droplet.xml');b=parse_xml(ROOT/'examples/soot_dem_levelset.xml')
        for c in (a,b):
            self.assertEqual(c['model']['soot_dem']['edges'],[(0,1),(1,2)])
            self.assertEqual(c['model']['contact'][:3],[0,0,0])
            self.assertTrue(prepared_text(c).startswith('PFDEM_INPUT 2\n'))
        self.assertEqual(a['model']['bodies'],b['model']['bodies'])
        self.assertEqual(a['model']['mode'],'droplets');self.assertEqual(b['model']['mode'],'levelset')
    def test_legacy_soot_neck_vtk(self):
        p=self.path/'necks.vtk';p.write_text('''# vtk DataFile Version 4.0
Generated by libgran
ASCII
DATASET POLYDATA
POINTS 2 FLOAT
0 0 0 1 0 0
POINT_DATA 2
FIELD FieldData 2
normals 3 2 double
1 0 0 1 0 0
connections 2 2 int
1 3 5 7
''')
        self.assertEqual(neck_edges(p,3),[(0,1),(1,2)])
        p.write_text(p.read_text().replace('1 3 5 7','1 3 5 8'))
        with self.assertRaises(ValueError):neck_edges(p,3)
    def test_no_double_contacts_and_no_polydisperse_fallback(self):
        base='<pf_dem><fluid dx=".1"/><particle radius=".24"/><particle x=".48" radius=".24"/><soot_dem/><liquid mode="droplets"><droplet radius=".6"/></liquid></pf_dem>'
        p=self.path/'input.xml';p.write_text(base.replace('<soot_dem/>','<contacts stiffness="1"/><soot_dem/>'))
        with self.assertRaisesRegex(ValueError,'combine'):parse_xml(p)
        p.write_text(base.replace('x=".48" radius=".24"','x=".48" radius=".25"'))
        with self.assertRaisesRegex(ValueError,'equal'):parse_xml(p)
    def test_necks_none_auto_and_graph_affect_signature(self):
        base='<pf_dem><fluid/><particle radius=".24"/><particle x=".48" radius=".24"/><soot_dem/><liquid mode="droplets"><droplet radius=".6"/></liquid>NECKS</pf_dem>'
        p=self.path/'run.xml';p.write_text(base.replace('NECKS','<necks mode="auto"/>'));a=parse_xml(p)
        p.write_text(base.replace('NECKS','<necks mode="none"/>'));b=parse_xml(p)
        self.assertEqual(a['model']['soot_dem']['neck_mode'],1)
        self.assertEqual(b['model']['soot_dem']['neck_mode'],0)
        self.assertNotEqual(a['signature'],b['signature'])
if __name__=='__main__':unittest.main()
